// Compress the Blender exports (tools/3d/out/*.glb) into small web models (models/*.glb),
// and write js/models-data.js so the 3D also works when index.html is opened from disk (file://).
//
//   npm run build:models
import { readFile, writeFile, stat } from "node:fs/promises";
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, meshopt, prune, quantize, simplify, textureCompress, weld } from "@gltf-transform/functions";
import { MeshoptDecoder, MeshoptEncoder, MeshoptSimplifier } from "meshoptimizer";
import sharp from "sharp";

const MODELS = [
    { name: "vitalcheer-device", ratio: 0.7, error: 0.0004 },
    { name: "iv-set", ratio: 0.6, error: 0.0008 },
];

await Promise.all([MeshoptDecoder.ready, MeshoptEncoder.ready, MeshoptSimplifier.ready]);
const io = new NodeIO()
    .registerExtensions(ALL_EXTENSIONS)
    .registerDependencies({ "meshopt.decoder": MeshoptDecoder, "meshopt.encoder": MeshoptEncoder });

const embedded = {};
for (const { name, ratio, error } of MODELS) {
    const src = `tools/3d/out/${name}.glb`;
    const dst = `models/${name}.glb`;
    const doc = await io.read(src);
    await doc.transform(
        dedup(),
        prune({ keepLeaves: true }), // keep empty named groups the site animates
        weld(),
        simplify({ simplifier: MeshoptSimplifier, ratio, error }),
        textureCompress({ encoder: sharp, targetFormat: "webp", resize: [1024, 1024] }),
        quantize(),
        meshopt({ encoder: MeshoptEncoder, level: "medium" }),
    );
    await io.write(dst, doc);
    const before = (await stat(src)).size;
    const after = (await stat(dst)).size;
    console.log(`${name}: ${(before / 1024).toFixed(0)} KB -> ${(after / 1024).toFixed(0)} KB`);
    embedded[name] = (await readFile(dst)).toString("base64");
}

await writeFile(
    "js/models-data.js",
    "/* Generated by tools/build-models.mjs: base64 copies of the models, used only when the page is opened from disk (file://). */\n" +
        "window.__VC_MODELS = " + JSON.stringify(embedded) + ";\n",
);
console.log("wrote js/models-data.js");
